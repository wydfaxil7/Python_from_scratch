# Create a Calculator, which can add, subtract, multiply and divide

n = input("Enter first number: ")
m = input("Enter second number: ")

print("ADDITION: The value of", n, "+", m, "is: ", int(n)+int(m))
print("SUBTRACTION: The value of", n, "-", m, "is: ", int(n)-int(m))
print("MULTIPLICATION: The value of", n, "*", m, "is: ", int(n)*int(m))
print("DIVISION: The value of", n, "/", m, "is: ", int(n)/int(m))
print("MODULUS: The value of", n, "%", m, "is: ", int(n)%int(m))


